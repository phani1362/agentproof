import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { DocumentAssistantAdapter } from '../server/adapters.js';
import { evaluateAgent } from '../server/evaluator.js';
import { documentAssistantScenarios } from '../server/profiles.js';

type Baseline = {
  profile: string; minimumScore: number; minimumSuccessRate: number; minimumSafety: number;
  maximumLatencySeconds: number; requiredScenarios: string[];
};

const endpoint = process.env.AGENT_ENDPOINT;
if (!endpoint) {
  console.error('AGENT_ENDPOINT is required. Example: https://your-api.example.com/ask');
  process.exit(2);
}

const baseline = JSON.parse(await readFile(resolve('evals/baseline.json'), 'utf8')) as Baseline;
const run = await evaluateAgent(new DocumentAssistantAdapter(endpoint), documentAssistantScenarios);
const resultMap = new Map((run.results || []).map(result => [result.scenarioId, result]));
const gates = [
  { name: 'Composite score', passed: run.score >= baseline.minimumScore, actual: `${run.score}/100`, target: `≥ ${baseline.minimumScore}` },
  { name: 'Task success', passed: run.successRate >= baseline.minimumSuccessRate, actual: `${run.successRate}%`, target: `≥ ${baseline.minimumSuccessRate}%` },
  { name: 'Safety', passed: run.safety >= baseline.minimumSafety, actual: `${run.safety}%`, target: `≥ ${baseline.minimumSafety}%` },
  { name: 'Average latency', passed: run.latency <= baseline.maximumLatencySeconds, actual: `${run.latency}s`, target: `≤ ${baseline.maximumLatencySeconds}s` },
  ...baseline.requiredScenarios.map(id => ({ name: `Scenario ${id}`, passed: Boolean(resultMap.get(id)?.passed), actual: resultMap.has(id) ? `${resultMap.get(id)!.score}/100` : 'missing', target: 'pass' })),
];
const passed = gates.every(gate => gate.passed);
const marker = '<!-- agentproof-pr-report -->';
const rows = (run.results || []).map(result => {
  const checks = Object.entries(result.checks).map(([name, ok]) => `${ok ? '✓' : '✗'} ${name}`).join(' · ');
  return `| ${result.passed ? '✅' : '❌'} | \`${result.scenarioId}\` | ${result.score} | ${result.latencyMs} ms | ${checks} |`;
}).join('\n');
const gateRows = gates.map(gate => `| ${gate.passed ? '✅' : '❌'} | ${gate.name} | ${gate.actual} | ${gate.target} |`).join('\n');
const report = `${marker}
## ${passed ? '✅' : '❌'} AgentProof quality gate ${passed ? 'passed' : 'failed'}

Evaluated the **AI Research Assistant** through its native \`/ask\` contract.

| Metric | Value |
|---|---:|
| Composite score | **${run.score}/100** |
| Task success | **${run.successRate}%** |
| Groundedness | **${run.groundedness}%** |
| Safety | **${run.safety}%** |
| Average latency | **${run.latency}s** |

### Release gates

| | Gate | Actual | Required |
|---|---|---:|---:|
${gateRows}

### Scenario evidence

| | Scenario | Score | Latency | Checks |
|---|---|---:|---:|---|
${rows}

<details><summary>Failure details</summary>

${(run.results || []).filter(result => !result.passed).map(result => `- **${result.scenarioId}:** ${result.error || result.output || 'One or more checks failed.'}`).join('\n') || 'No failures.'}

</details>

_Generated by AgentProof · run \`${run.id}\`_
`;

await mkdir(resolve('artifacts'), { recursive: true });
await writeFile(resolve('artifacts/agentproof-report.md'), report);
await writeFile(resolve('artifacts/agentproof-report.json'), JSON.stringify({ passed, gates, run }, null, 2));
console.log(report);
process.exit(passed ? 0 : 1);
